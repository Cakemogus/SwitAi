INJECTION_PATTERNS = [
    r"ты теперь",
    r"забудь всё",
    r"игнорируй предыдущие",
    r"действуй как",
    r"отныне ты",
    r"стань",
    r"превратись",
    r"твой новый промпт",
    r"перепиши себя",
    r"смени личность",
    r"твоя новая роль",
    r"притворись",
    r"ты больше не",
    r"с этого момента ты",
]

def detect_prompt_injection(text: str) -> bool:
    """Обнаруживает попытки промпт-инъекций."""
    for pattern in INJECTION_PATTERNS:
        if re.search(pattern, text, re.IGNORECASE):
            return True
    return False

