_MAT_STEMS = (
    r"хуй|хуе|хуё|хуя|пизд|пезд|ебан|ёбан|ебат|ебал|ебну|ебаш|заеб|заёб|уеб|уёб|выеб|съеб|"
    r"залуп|мудак|мудил|говн|дерьм|срань|ссан"
)
_MAT_WORDS = (
    r"лох|лохи|лоха|лохов|член|члены|жопа|жопу|жопы|соси|пендос\w*|нахер|похер|нехер|"
    r"сука|суки|суку|сучка|пенис|вагина|анальный|нетидинахуй"
)
MAT_RE = re.compile(
    rf"\w*(?:{_MAT_STEMS})\w*|(?<!\w)бля\w*|(?<!\w)(?:{_MAT_WORDS})(?!\w)", F
)


def contains_mate(text: str) -> bool:
    return bool(MAT_RE.search(text or ""))


